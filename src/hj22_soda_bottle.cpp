/*
HJ22 汽水瓶
知识点：数学、模拟
时间限制：1 秒
空间限制：32 MB

样例 1：
输入：
3
10
81
0

输出：
1
5
40

样例说明：
第一组数据有 3 个空瓶，可以换 1 瓶汽水，无法继续兑换，最多喝到 1 瓶。
第二组数据的兑换过程如下：
1. 10 个空瓶换 3 瓶汽水，余下 1 个空瓶。
2. 喝完后共有 1 + 3 = 4 个空瓶，换 1 瓶汽水，余下 1 个空瓶。
3. 喝完后共有 2 个空瓶，再向老板借 1 个空瓶，换 1 瓶汽水。
   喝完后将得到的空瓶归还给老板。
一共可以喝到 3 + 1 + 1 = 5 瓶汽水。

描述：
某商店规定：三个空汽水瓶可以换一瓶汽水，允许向老板借空汽水瓶，
但是借来的空瓶必须归还。
小张手上有 n 个空汽水瓶，求她最多可以喝到多少瓶汽水。

输入描述：
本题包含 1 <= T <= 10 组测试数据，确切组数未知，需要持续读入直到结束标记。
每组数据在一行上输入一个整数 n（0 <= n <= 100），表示小张手上的空瓶数量。
特别地，n = 0 表示输入结束，应立即退出，不需要处理或输出该组数据。

输出描述：
对于每组测试数据，单独一行输出一个整数，表示小张最多可以喝到的汽水数量。
*/
#include <iostream>
using namespace std;

int main()
{
    int n;
    while (cin >> n && n != 0) {
        cout << n / 2 << '\n';
    }
}
