/*
HJ7 取近似值

知识点：语法题、基础数学

样例 1：
输入：5.5
输出：6
说明：5.5 的小数部分大于等于 0.5，因此向上取整为 6。

样例 2：
输入：2.499
输出：2
说明：2.499 的小数部分小于 0.5，因此向下取整为 2。

描述：
对于给定的正实数 x，输出其四舍五入后的整数。更具体地说，若 x 的小数部分
大于等于 0.5，则输出向上取整后的整数；否则输出向下取整后的整数。

输入描述：
输入一个小数点后位数不超过 5 位的实数 x（0 < x <= 20）。保证实数不存在
前导零和后导零。

输出描述：
在一行上输出一个整数，代表 x 四舍五入后的结果。
*/
#include <iostream>
using namespace std;
int main()
{
    double x;
    const double eps = 1e-8;
    cin >>x;
    int i = static_cast<int> (x);
    if( 0.5 + i - x >eps){
        cout << i;
    }else{
        cout <<i + 1;
    }
    return 0;
}
