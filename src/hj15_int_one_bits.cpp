/*
HJ15 求 int 型正整数在内存中存储时 1 的个数

知识点：位运算

样例 1：
输入：
10

输出：
2

说明：
十进制 10 的二进制表示为 1010，其中包含 2 个 1。

样例 2：
输入：
0

输出：
0

描述：
对于给定的 int 型的十进制整数 n，统计其在内存中存储时 1 的个数。
换句话说，即统计其二进制表示中 1 的个数。

输入描述：
在一行上输入一个整数 n（0 <= n < 2^31），代表给定的数字。

输出描述：
在一行上输出一个整数，代表 n 的二进制表示中 1 的个数。
*/
#include <iostream>

int main()
{
    unsigned int n;
    std::cin >> n;

    int count = 0;
    while (n != 0)
    {
        count += n & 1u;
        n >>= 1;
    }

    std::cout << count;
    return 0;
}